import { useEffect, useMemo, useState } from "react";
import { Canvas } from "@react-three/fiber";
import { OrbitControls, RoundedBox, Html, ContactShadows } from "@react-three/drei";
import { Maximize2 } from "lucide-react";
import { useStore } from "../store";
import type { Bin, Grid } from "../types";
import { GRID_UNIT, HEIGHT_UNIT } from "../types";
import { filament as getFilament, type Filament } from "../lib/filament";

/*
 * LIVE preview — built entirely from three.js primitives so it's instant and
 * needs no backend round-trip. This is intentionally NOT the export geometry:
 * the watertight CAD solids (build123d) are still the source of truth and are
 * generated by the backend only when you export. Here we just want a fast,
 * faithful-enough visualisation while editing, lit like a product shot.
 */

const CLEARANCE = 0.5; // bin is 0.5mm under the cell pitch
const PLATE_H = 5.85; // thin baseplate height (matches constants.py)
const VWALL = 1.6; // visual wall thickness (exaggerated slightly for clarity)
const SELECT = "#0a6ce4";

function useDark() {
  const q = "(prefers-color-scheme: dark)";
  const [dark, setDark] = useState(() => typeof window !== "undefined" && !!window.matchMedia?.(q).matches);
  useEffect(() => {
    const m = window.matchMedia?.(q);
    if (!m) return;
    const on = () => setDark(m.matches);
    m.addEventListener("change", on);
    return () => m.removeEventListener("change", on);
  }, []);
  return dark;
}

// Bin centre in plate coordinates (mm). Plate is centred on the origin.
function binCentre(grid: Grid, b: Bin): [number, number, number] {
  const x = -(grid.cols * GRID_UNIT) / 2 + (b.x + b.w / 2) * GRID_UNIT;
  const z = -(grid.rows * GRID_UNIT) / 2 + (b.y + b.d / 2) * GRID_UNIT;
  return [x, 0, z];
}

function BinMesh({ grid, bin, selected, labels, fil }: { grid: Grid; bin: Bin; selected: boolean; labels: boolean; fil: Filament }) {
  const w = bin.w * GRID_UNIT - CLEARANCE;
  const d = bin.d * GRID_UNIT - CLEARANCE;
  const h = bin.heightU * HEIGHT_UNIT;
  const [cx, , cz] = binCentre(grid, bin);
  const yBase = PLATE_H; // sits on top of the plate

  // An open-topped shell so the cavity reads as hollow: a short solid base,
  // then four perimeter walls with no top face.
  const baseH = Math.min(4, h * 0.35);
  const wallH = Math.max(0.5, h - baseH);
  const wallCY = yBase + baseH + wallH / 2;
  const cavY = yBase + baseH;
  const innerW = w - 2 * VWALL;
  const innerD = d - 2 * VWALL;

  const body = fil.face;
  const inner = fil.deep;
  const emissive = selected ? SELECT : "#000000";
  const ei = selected ? 0.28 : 0;
  const mat = { metalness: 0.02, roughness: 0.48, emissive, emissiveIntensity: ei };

  // Imported community models aren't generated here — a translucent block
  // shows the reserved footprint, with the model's thumbnail floating above.
  if (bin.kind === "model") {
    const m = bin.model;
    return (
      <group position={[cx, 0, cz]}>
        <RoundedBox args={[w, h, d]} radius={3} smoothness={3} position={[0, yBase + h / 2, 0]}>
          <meshStandardMaterial color={selected ? SELECT : "#c9d6ee"} metalness={0} roughness={0.35} transparent opacity={0.72} />
        </RoundedBox>
        {labels && m && (
          <Html position={[0, yBase + h + 6, 0]} center distanceFactor={520} occlude={false} zIndexRange={[10, 0]}>
            <div style={{ width: 104, transform: "translateY(-50%)", pointerEvents: "none", textAlign: "center", fontFamily: "var(--font)" }}>
              {m.thumbnail ? (
                <img src={m.thumbnail} alt="" referrerPolicy="no-referrer"
                  style={{ width: 96, height: 72, objectFit: "cover", borderRadius: 12, boxShadow: "0 8px 24px rgba(0,0,0,.25), 0 0 0 1px rgba(0,0,0,.06)", background: "#fff", margin: "0 auto" }} />
              ) : null}
              <div style={{ marginTop: 6, display: "inline-block", padding: "3px 8px", borderRadius: 999, background: "var(--tip)", color: "var(--on-tip)", fontSize: 10.5, fontWeight: 600, lineHeight: 1.2 }}>
                {m.title.length > 32 ? m.title.slice(0, 30) + "…" : m.title}
              </div>
            </div>
          </Html>
        )}
      </group>
    );
  }

  if (bin.solid) {
    return (
      <group position={[cx, 0, cz]}>
        <RoundedBox args={[w, h, d]} radius={3.2} smoothness={3} position={[0, yBase + h / 2, 0]}>
          <meshStandardMaterial color={body} {...mat} />
        </RoundedBox>
      </group>
    );
  }

  const walls: { pos: [number, number, number]; size: [number, number, number] }[] = [
    { pos: [0, wallCY, -d / 2 + VWALL / 2], size: [w, wallH, VWALL] },
    { pos: [0, wallCY, d / 2 - VWALL / 2], size: [w, wallH, VWALL] },
    { pos: [-w / 2 + VWALL / 2, wallCY, 0], size: [VWALL, wallH, d - 2 * VWALL] },
    { pos: [w / 2 - VWALL / 2, wallCY, 0], size: [VWALL, wallH, d - 2 * VWALL] },
  ];
  const dividers: { pos: [number, number, number]; size: [number, number, number] }[] = [];
  for (let k = 1; k < bin.comp.cols; k++) {
    const lx = -innerW / 2 + (innerW * k) / bin.comp.cols;
    dividers.push({ pos: [lx, wallCY, 0], size: [VWALL, wallH, innerD] });
  }
  for (let k = 1; k < bin.comp.rows; k++) {
    const lz = -innerD / 2 + (innerD * k) / bin.comp.rows;
    dividers.push({ pos: [0, wallCY, lz], size: [innerW, wallH, VWALL] });
  }

  return (
    <group position={[cx, 0, cz]}>
      <RoundedBox args={[w, baseH, d]} radius={3.2} smoothness={3} position={[0, yBase + baseH / 2, 0]}>
        <meshStandardMaterial color={body} {...mat} />
      </RoundedBox>
      <mesh position={[0, cavY + 0.3, 0]}>
        <boxGeometry args={[innerW, 0.6, innerD]} />
        <meshStandardMaterial color={inner} metalness={0} roughness={0.8} emissive={emissive} emissiveIntensity={ei} />
      </mesh>
      {walls.map((wl, i) => (
        <mesh key={`w${i}`} position={wl.pos}>
          <boxGeometry args={wl.size} />
          <meshStandardMaterial color={body} {...mat} />
        </mesh>
      ))}
      {dividers.map((dv, i) => (
        <mesh key={`d${i}`} position={dv.pos}>
          <boxGeometry args={dv.size} />
          <meshStandardMaterial color={body} {...mat} />
        </mesh>
      ))}
      {bin.label && (
        <mesh position={[0, yBase + h - 1, -d / 2 + 6]}>
          <boxGeometry args={[Math.min(w * 0.5, 26), 2, 11]} />
          <meshStandardMaterial color={body} {...mat} />
        </mesh>
      )}
    </group>
  );
}

function PlateMesh({ grid, dark }: { grid: Grid; dark: boolean }) {
  const w = grid.cols * GRID_UNIT;
  const d = grid.rows * GRID_UNIT;
  const cells = useMemo(() => {
    const arr: [number, number][] = [];
    for (let i = 0; i < grid.cols; i++)
      for (let j = 0; j < grid.rows; j++)
        arr.push([-w / 2 + (i + 0.5) * GRID_UNIT, -d / 2 + (j + 0.5) * GRID_UNIT]);
    return arr;
  }, [grid.cols, grid.rows, w, d]);

  return (
    <group>
      <RoundedBox args={[w, PLATE_H, d]} radius={4} smoothness={3} position={[0, PLATE_H / 2, 0]}>
        <meshStandardMaterial color={dark ? "#3a3a3e" : "#f4f4f6"} metalness={0} roughness={0.55} />
      </RoundedBox>
      {cells.map(([x, z], i) => (
        <mesh key={i} position={[x, PLATE_H - 0.6, z]}>
          <boxGeometry args={[GRID_UNIT - 3, 1.4, GRID_UNIT - 3]} />
          <meshStandardMaterial color={dark ? "#2c2c30" : "#dfdfe5"} metalness={0} roughness={0.8} />
        </mesh>
      ))}
    </group>
  );
}

export function Preview3D({ compact = false }: { compact?: boolean }) {
  const { grid, bins, selectedId, filament } = useStore();
  const dark = useDark();
  const fil = getFilament(filament);
  const radius = Math.max(grid.cols, grid.rows) * GRID_UNIT;
  const bg = dark ? "#121214" : "#ebebef";

  return (
    <div style={{ position: "relative", width: "100%", height: "100%", background: `radial-gradient(120% 90% at 50% 20%, ${dark ? "#1c1c1f" : "#fafafc"}, ${bg})` }}>
      <Canvas
        camera={{ position: [radius * 0.85, radius * 0.95, radius * 1.2], fov: 32, near: 1, far: radius * 20 }}
        dpr={[1, 2]}
        gl={{ alpha: true, antialias: true }}
      >
        <ambientLight intensity={dark ? 0.6 : 0.9} />
        <hemisphereLight args={["#ffffff", dark ? "#202024" : "#d9dbe3", 0.7]} />
        <directionalLight position={[radius * 0.6, radius * 1.4, radius * 0.9]} intensity={1.7} />
        <directionalLight position={[-radius, radius * 0.5, -radius * 0.6]} intensity={0.55} />

        <group>
          <PlateMesh grid={grid} dark={dark} />
          {bins.map((b) => (
            <BinMesh key={b.id} grid={grid} bin={b} selected={b.id === selectedId} labels={!compact} fil={fil} />
          ))}
        </group>
        {!compact && (
          <>
            <Html position={[0, 0, (grid.rows * GRID_UNIT) / 2 + 14]} center zIndexRange={[5, 0]}>
              <span className="dim3d num">{grid.cols * GRID_UNIT} mm</span>
            </Html>
            <Html position={[(grid.cols * GRID_UNIT) / 2 + 14, 0, 0]} center zIndexRange={[5, 0]}>
              <span className="dim3d num">{grid.rows * GRID_UNIT} mm</span>
            </Html>
          </>
        )}
        <ContactShadows position={[0, -0.05, 0]} scale={radius * 2.6} blur={2.6} far={radius * 0.5} opacity={dark ? 0.6 : 0.35} resolution={512} />

        <OrbitControls enablePan={!compact} makeDefault target={[0, PLATE_H, 0]} maxPolarAngle={Math.PI * 0.48} />
      </Canvas>

      {!compact && (
        <div className="float hint-3d">Drag to orbit · Scroll to zoom{bins.length ? "" : " · Add bins in 2D"}</div>
      )}
    </div>
  );
}

export function Pip3D() {
  const setView = useStore((s) => s.setView);
  return (
    <div className="float pip" aria-label="3D preview">
      <div className="pip-head">
        <span>3D preview</span>
        <button type="button" className="btn btn-icon" onClick={() => setView("3d")} aria-label="Open full 3D view" title="Open full 3D view">
          <Maximize2 size={13} />
        </button>
      </div>
      <Preview3D compact />
    </div>
  );
}
